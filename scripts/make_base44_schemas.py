def field_type(s: pd.Series, name: str):
    s = s.dropna()
    if name in ("run_id",) or s.empty:
        return {"type": "string"}
    if s.astype(str).str.lower().isin(["true", "false"]).all():
        return {"type": "boolean"}
    num = pd.to_numeric(s, errors="coerce")
    if num.notna().all():
        if (num % 1 == 0).all() and not name.endswith(("_z", "_r2", "_r", "rate", "pct", "svi")):
            return {"type": "integer"} if "fips" not in name else {"type": "string"}
        return {"type": "number"}
    if any(k in name for k in ("week", "date", "as_of", "utc")):
        return {"type": "string", "format": "date"}
    return {"type": "string"}


def main(export_dir, schema_dir):
    export_dir, schema_dir = Path(export_dir), Path(schema_dir)
    schema_dir.mkdir(parents=True, exist_ok=True)
    allin = {}
    for f in sorted(export_dir.glob("*.csv")):
        df = pd.read_csv(f, dtype={"county_fips": str}, low_memory=False)
        props = {c: field_type(df[c], c) for c in df.columns}
        schema = {"name": f.stem, "type": "object", "description": DESCRIPTIONS.get(f.stem, ""),
                  "properties": props, "required": ["run_id", "data_as_of"]}
        (schema_dir / f"{f.stem}.json").write_text(json.dumps(schema, indent=2))
        allin[f.stem] = schema
    (schema_dir / "_all_entities.json").write_text(json.dumps(allin, indent=2))
    print(f"{len(allin)} entity schemas written to {schema_dir}")


if __name__ == "__main__":
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    main(sys.argv[1], sys.argv[2])
