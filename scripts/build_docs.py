def language_table():
    """Count real source lines per language, straight off the working tree."""
    tally = {}
    for p in ROOT.rglob("*"):
        if not p.is_file() or p.suffix not in LANG_ROLE:
            continue
        if any(part in SKIP_DIRS for part in p.relative_to(ROOT).parts):
            continue
        try:
            n = sum(1 for line in p.read_text(encoding="utf-8", errors="ignore").splitlines()
                    if line.strip())
        except Exception:
            continue
        name, role = LANG_ROLE[p.suffix]
        files, lines, _ = tally.get(name, (0, 0, role))
        tally[name] = (files + 1, lines + n, role)
    rows = [[name, f"{files:,}", f"{lines:,}", role]
            for name, (files, lines, role) in
            sorted(tally.items(), key=lambda kv: -kv[1][1])]
    return table(rows, ["Language", "Files", "Lines", "Used for"])


def python_version():
    """The interpreter the workflow pins, so the document cannot claim another."""
    for wf in sorted((ROOT / ".github" / "workflows").glob("*.yml")):
        m = re.search(r"python-version:\s*[\"']?([0-9.]+)", wf.read_text(encoding="utf-8"))
        if m:
            return m.group(1)
    return None


def package_table():
    """requirements.txt, with each entry's trailing comment kept as its note."""
    req = ROOT / "requirements.txt"
    if not req.exists():
        return None
    rows, group = [], ""
    for line in req.read_text(encoding="utf-8").splitlines():
        s = line.strip()
        if not s:
            continue
        if s.startswith("#"):
            # Group headings carry a parenthetical version in the file; drop it
            # here so the column does not pin a version number that moves.
            group = re.sub(r"\s*\(.*?\)", "", s.lstrip("# ").strip())
            continue
        spec, _, note = s.partition("#")
        spec = spec.strip()
        m = re.match(r"([A-Za-z0-9_.\-]+)(.*)", spec)
        if not m:
            continue
        rows.append([f"`{m.group(1)}`", m.group(2).strip() or "any", group, note.strip()])
    return table(rows, ["Package", "Version", "Needed by", "Note"]) if rows else None


