def kind_of(series):
    """A readable type for a column, from its values."""
    if pd.api.types.is_bool_dtype(series):
        return "boolean"
    if pd.api.types.is_integer_dtype(series):
        return "integer"
    if pd.api.types.is_float_dtype(series):
        return "number"
    s = series.dropna().astype(str)
    if len(s) and s.str.match(r"^\d{4}-\d{2}-\d{2}").mean() > 0.8:
        return "date"
    return "text"


def example_of(series):
    s = series.dropna()
    if not len(s):
        return ""
    v = s.iloc[0]
    if isinstance(v, float):
        v = f"{v:.4g}"
    v = str(v).replace("|", "\\|")
    return f"`{v[:40]}`" + ("…" if len(str(v)) > 40 else "")


